  r.SetToggleCommandState(section, command, 0)
  r.RefreshToolbar2(section, command)
  if cursor and r.JS_Mouse_SetCursor then
    r.JS_Mouse_SetCursor(r.JS_Mouse_LoadCursor(32512))
  end
end
