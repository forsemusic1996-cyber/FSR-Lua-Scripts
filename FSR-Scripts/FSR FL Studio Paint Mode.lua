local function delete_automation(targets)
  if not next(targets) then return false end
  -- The native delete action affects every selected automation item. Temporarily
  -- select only the targets and restore surviving selections by shifted index.
  local states = {}
  for t = -1, r.CountTracks(eraser.project) - 1 do
    local track = t == -1 and r.GetMasterTrack(eraser.project) or r.GetTrack(eraser.project, t)
    for e = 0, r.CountTrackEnvelopes(track) - 1 do
      local env = r.GetTrackEnvelope(track, e)
      local count = r.CountAutomationItems(env)
      if count > 0 then
        local state = {env = env, selected = {}, removed = targets[env] or {}}
        states[#states + 1] = state
        for i = 0, count - 1 do
          state.selected[i] = r.GetSetAutomationItemInfo(env, i, "D_UISEL", 0, false)
          r.GetSetAutomationItemInfo(env, i, "D_UISEL", state.removed[i] and 1 or 0, true)
        end
        state.count = count
      end
    end
  end
  erase_undo()
  r.Main_OnCommand(42086, 0) -- Envelope: delete selected automation items.
  for _, state in ipairs(states) do
    local shifted = 0
    for i = 0, state.count - 1 do
      if state.removed[i] then shifted = shifted + 1
      elseif i - shifted < r.CountAutomationItems(state.env) then
        r.GetSetAutomationItemInfo(state.env, i - shifted, "D_UISEL", state.selected[i], true)
      end
    end
  end
  eraser.snapshot = nil
  return true
end

local function segment_hits_rect(a, b, xmin, xmax, ymin, ymax)
  -- Clip the entire pointer segment, rather than sampling individual pixels.
  -- Tiny items crossed by a fast movement are therefore still included.
  local lo, hi = 0, 1
  local function slab(p, delta, low, high)
    if math.abs(delta) < EPS then return p >= low and p <= high end
    local first, last = (low - p) / delta, (high - p) / delta
    if first > last then first, last = last, first end
    lo, hi = math.max(lo, first), math.min(hi, last)
    return lo <= hi
  end
  return slab(a.time, b.time - a.time, xmin + EPS, xmax - EPS)
    and slab(a.y, b.y - a.y, ymin + 0.001, ymax - 0.001)
end

