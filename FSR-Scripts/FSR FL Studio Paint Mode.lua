local function erase_snapshot()
  if eraser.snapshot then return eraser.snapshot end
  local entries = {}
  local _, _, top, _, bottom = r.JS_Window_GetClientRect(arrange)
  local height = bottom - top
  for t = -1, r.CountTracks(project) - 1 do
    local track = t == -1 and r.GetMasterTrack(project) or r.GetTrack(project, t)
    local track_y = r.GetMediaTrackInfo_Value(track, "I_TCPY")
    local track_h = r.GetMediaTrackInfo_Value(track, "I_WNDH")
    if track_h > 0 and track_y < height and track_y + track_h > 0 then
      if t >= 0 then
        for i = 0, r.CountTrackMediaItems(track) - 1 do
          local item = r.GetTrackMediaItem(track, i)
          local item_h = r.GetMediaItemInfo_Value(item, "I_LASTH")
          local item_y = track_y + r.GetMediaItemInfo_Value(item, "I_LASTY")
          if item_h > 0 and r.GetMediaItemInfo_Value(item, "B_FIXEDLANE_HIDDEN") == 0 then
            local start = r.GetMediaItemInfo_Value(item, "D_POSITION")
            entries[#entries + 1] = {item = item, start = start,
              stop = start + r.GetMediaItemInfo_Value(item, "D_LENGTH"),
              ymin = item_y, ymax = item_y + item_h}
          end
        end
      end
      for e = 0, r.CountTrackEnvelopes(track) - 1 do
        local env = r.GetTrackEnvelope(track, e)
        local env_h = r.GetEnvelopeInfo_Value(env, "I_TCPH_USED")
        local env_y = track_y + r.GetEnvelopeInfo_Value(env, "I_TCPY_USED")
        if env_h > 0 then
          for i = 0, r.CountAutomationItems(env) - 1 do
            local start = r.GetSetAutomationItemInfo(env, i, "D_POSITION", 0, false)
            entries[#entries + 1] = {env = env, index = i, start = start,
              stop = start + r.GetSetAutomationItemInfo(env, i, "D_LENGTH", 0, false),
              ymin = env_y, ymax = env_y + env_h}
          end
        end
      end
    end
  end
  eraser.snapshot = entries
  return entries
end

local function erase_targets_at_point(point, clear_empty)
  local item = r.GetItemFromPoint(point.x, point.screen_y, true)
  if item then return delete_media_item(item) end
  for _, entry in ipairs(erase_snapshot()) do
    if entry.env and point.time >= entry.start and point.time < entry.stop
      and point.y >= entry.ymin and point.y < entry.ymax then
      return delete_automation({[entry.env] = {[entry.index] = true}})
    end
  end
  -- Clear selection only when the RMB gesture STARTS on empty space.
  -- Crossing empty space during an erase drag must not clear surviving selection.
  -- A locked item still counts as an item, even though it cannot be deleted.
  if clear_empty and r.CountSelectedMediaItems(eraser.project) > 0 then
    r.SelectAllMediaItems(eraser.project, false)
    return true
  end
  return false
end

local function erase_to(point, first)
  if not point then eraser.last = nil; return end
  if not first and eraser.last and math.abs(point.time - eraser.last.time) < EPS
    and math.abs(point.y - eraser.last.y) < 0.001 then return end
  local changed = false
  local key = viewport_key()
  if key ~= eraser.view or r.GetProjectStateChangeCount(project) ~= eraser.cache_state then
    eraser.snapshot = nil
    if key ~= eraser.view then eraser.last = nil end
    eraser.view = key
  end
  r.PreventUIRefresh(1)
  local ok, err = xpcall(function()
    if first or not eraser.last then changed = erase_targets_at_point(point, first)
    else
      local automation = {}
      for _, entry in ipairs(erase_snapshot()) do
        if segment_hits_rect(eraser.last, point, entry.start, entry.stop, entry.ymin, entry.ymax) then
          if entry.item then
            if delete_media_item(entry.item) then changed = true end
          else
            automation[entry.env] = automation[entry.env] or {}
            automation[entry.env][entry.index] = true
          end
        end
      end
      if delete_automation(automation) then changed = true end
    end
  end, debug.traceback)
  r.PreventUIRefresh(-1)
  eraser.last = point
  eraser.cache_state = r.GetProjectStateChangeCount(project)
  if changed then r.UpdateArrange() end
  if not ok then error(err) end
end

local function begin_eraser(point)
  eraser = {project = project, deleted = {},
    cache_state = r.GetProjectStateChangeCount(project)}
  erase_to(point, true)
end

local function show_right_menu()
  local window, segment, details = r.BR_GetMouseCursorContext()
  local x, y = r.GetMousePosition()
  if window == "arrange" and segment == "envelope" then
    local env = r.BR_GetMouseCursorContext_Envelope()
    local time = r.BR_GetMouseCursorContext_Position()
    local automation = false
    if env then
      for i = 0, r.CountAutomationItems(env) - 1 do
        local start = r.GetSetAutomationItemInfo(env, i, "D_POSITION", 0, false)
        local stop = start + r.GetSetAutomationItemInfo(env, i, "D_LENGTH", 0, false)
        if time >= start and time < stop then automation = true; break end
      end
    end
    r.ShowPopupMenu(automation and "envelope_item" or "envelope", x, y, nil, 0, 0, 0)
  elseif window == "arrange" then
    r.ShowPopupMenu(details == "item" and "item" or "ruler", x, y, nil, 0, 0, 0)
  elseif window == "ruler" then
    r.ShowPopupMenu("ruler", x, y, nil, 0, 0, 0)
  end
end

local function tick()
  local current_project = r.EnumProjects(-1, "")
  if current_project ~= project then
    finish_stroke()
    finish_eraser()
    project, source_cache, native_drag, right_mode, media_drag = current_project, nil, false, nil, false
    source_items, source_items_state = {}, nil
    event_list()
  end
  if not r.JS_Window_IsWindow(arrange) then cleanup(); return end
  local physical_mouse = r.JS_Mouse_GetState(63)
  if (physical_mouse & 1) ~= 0 then
    if focus_is_media_explorer() then media_drag = true end
  else
    media_drag = false
  end
  if media_drag and stroke then
    drain(math.huge)
    finish_stroke()
    native_drag = true
  end
  -- Resolve the drop before the next click can start a painting stroke.
  observe_imported_sample()
  for _, event in ipairs(event_list()) do
    local x, y = r.JS_Window_ClientToScreen(arrange, event.x, event.y)
    if event.msg == "WM_CONTEXTMENU" then
      -- Keyboard context-menu requests use (-1, -1) screen coordinates.
      if right_mode == "native" or (event.x == -1 and event.y == -1) then forward(event) end
    elseif event.msg == "WM_RBUTTONUP" then
      if eraser then
        erase_to(erase_pointer(x, y), false)
        finish_eraser()
      elseif right_mode == "native" then forward(event) end
      -- Keep mode until WM_CONTEXTMENU arrives, so the delete gesture won't
      -- unexpectedly open REAPER's context menu after mouse release.
    elseif event.msg == "WM_RBUTTONDOWN" or event.msg == "WM_RBUTTONDBLCLK" then
      if stroke then drain(math.huge); finish_stroke() end
      if eraser then finish_eraser() end
      local modifiers = r.JS_Mouse_GetState(60)
      if (event.wlow & 4) ~= 0 then modifiers = modifiers | 8 end
      if (event.wlow & 8) ~= 0 then modifiers = modifiers | 4 end
      local point = erase_pointer(x, y)
      local razor_hit = point and inside_razor(hit(x, y, false), false)
      if modifiers == 8 then
        right_mode = "menu"
        show_right_menu()
      elseif razor_hit and modifiers == 0 and point then
        right_mode = "razor_clear"
        clear_razor_edits()
      elseif modifiers ~= 0 or native_drag or not point then
        right_mode = "native"
        forward(event)
      else
        right_mode = "erase"
        begin_eraser(point)
      end
    elseif event.msg == "WM_LBUTTONUP" then
      if media_drag then
        if stroke then drain(math.huge); finish_stroke() end
        forward(event)
      elseif stroke then
        local release_hit = stroke_hit(x, y, false)
        local waiting_at_razor_origin = stroke.razor_drag
          and release_hit and math.abs(release_hit.time - stroke.mouse_anchor)
            < stroke.source.step - EPS
        if not waiting_at_razor_origin then
          enqueue(release_hit)
          follow_razor_hit(release_hit)
        end
        stroke.released = true
      elseif native_drag then forward(event) end
      native_drag = false
    else
      if eraser then finish_eraser(); right_mode = "blocked" end
      if stroke then drain(math.huge); finish_stroke() end
      if media_drag and (event.msg == "WM_LBUTTONDOWN" or event.msg == "WM_LBUTTONDBLCLK") then
        if stroke then drain(math.huge); finish_stroke() end
        native_drag = true
        forward(event)
      else
        local h = hit(x, y, false)
        local modifiers = r.JS_Mouse_GetState(60)
        local clicked = h and r.GetItemFromPoint(x, y, true)
        local razor_source = CONFIG.mode == "copy" and source_from_razor() or nil
        local razor_drag = source_razor_contains(razor_source, h)
        local razor_brush = razor_drag ~= nil
        if clicked and CONFIG.mode == "copy" then source_cache = source_from_item(clicked) end
        local edge_native = (event.msg == "WM_LBUTTONDOWN" or event.msg == "WM_LBUTTONDBLCLK")
          and h and not razor_brush
          and (near_item_edge(x, y) or near_razor_edge(x, y, h))
        local normal_edit = (clicked ~= nil and not razor_drag)
          or (event.wlow & 12) ~= 0 or (modifiers & 44) ~= 0
        if edge_native then
          native_drag = true
          forward(event)
        elseif h and not normal_edit then
          native_drag = not begin_stroke(h, (modifiers & 16) ~= 0,
            razor_source, razor_drag)
          if native_drag then forward(event) end
        else
          native_drag = true
          forward(event)
        end
      end
    end
  end
  local mouse = r.JS_Mouse_GetState(63)
  local x, y = r.GetMousePosition()
  local h = hit(x, y, true)
  if stroke then
    if not stroke.released then
      local held = (mouse & 1) ~= 0
      local current_hit = stroke_hit(x, y, held)
      local waiting_at_razor_origin = stroke.razor_drag
        and current_hit and math.abs(current_hit.time - stroke.mouse_anchor)
          < stroke.source.step - EPS
      if not waiting_at_razor_origin then
        enqueue(current_hit)
        follow_razor_hit(current_hit)
      end
      if not held then stroke.released = true end
    end
    drain(CONFIG.max_stamps_per_frame)
    if stroke.released and #queue == 0 then finish_stroke() end
  end
  if eraser then
    erase_to(erase_pointer(x, y), false)
    if (mouse & 2) == 0 then finish_eraser() end
  end
  if cursor_hook then
    local hovered = h and r.GetItemFromPoint(x, y, true)
    local selected_hover = hovered and r.IsMediaItemSelected(hovered)
    local razor_hover = CONFIG.razor_source and h and inside_media_razor(h) or false
    local edge_hover = h and not razor_hover and near_item_edge(x, y) or false
    local razor_edge_hover = h and not razor_hover and near_razor_edge(x, y, h) or false
    local wanted
    if right_mode == "erase" and (mouse & 2) ~= 0 and r.JS_Window_FromPoint(x, y) == arrange then
      wanted = delete_cursor
    elseif CONFIG.brush_cursor and not edge_hover and not razor_edge_hover
      and not media_drag and h and not native_drag
      and (stroke or not selected_hover or razor_hover)
      and (((mouse & 1) == 0) or stroke)
      and (mouse & 46) == 0 then
      wanted = cursor
    end
    local blocked = wanted ~= nil
    if blocked ~= cursor_blocked then
      r.JS_WindowMessage_PassThrough(arrange, "WM_SETCURSOR", not blocked)
      cursor_blocked = blocked
    end
    if wanted then r.JS_Mouse_SetCursor(wanted) end
  end
  r.defer(function()
    local ok, err = xpcall(tick, debug.traceback)
    if not ok then cleanup(); r.MB(err, TITLE, 0) end
  end)
end
local ok, err = xpcall(tick, debug.traceback)
if not ok then cleanup(); r.MB(err, TITLE, 0) end

