local function load_embedded_cursor(hex, filename)
  local data = hex:gsub("%s+", ""):gsub("..", function(pair)
    return string.char(tonumber(pair, 16))
  end)
  local directory = r.GetResourcePath() .. "/Data"
  r.RecursiveCreateDirectory(directory, 0)
  local path = directory .. "/" .. filename
  local file = io.open(path, "rb")
  local previous
  if file then previous = file:read("*a"); file:close() end
  if previous ~= data then
    local output, err = io.open(path, "wb")
    if not output then error("Cannot save brush cursor: " .. tostring(err)) end
    local ok, write_err = output:write(data)
    output:close()
    if not ok then error("Cannot write brush cursor: " .. tostring(write_err)) end
  end
  local cursor = r.JS_Mouse_LoadCursorFromFile(path)
  if not cursor then error("Cannot load embedded brush cursor.") end
  return cursor
end

local function valid_project(p)
  for i = 0, 1024 do
    local candidate = r.EnumProjects(i, "")
    if not candidate then return false end
    if candidate == p then return true end
  end
  return false
end

local function finish_stroke()
  if stroke and stroke.undo and valid_project(stroke.project) then
    r.Undo_EndBlock2(stroke.project, "Paint items (FL-style brush)", 4)
  end
  stroke = nil
  queue, qhead = {}, 1
end

