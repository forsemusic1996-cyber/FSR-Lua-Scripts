local function hit(x, y, check_window)
  if check_window and r.JS_Window_FromPoint(x, y) ~= arrange then return end
  local track, info = r.GetTrackFromPoint(x, y)
  if not track or track == r.GetMasterTrack(project) or (info & 255) ~= 0 then return end
  local mode = r.GetMediaTrackInfo_Value(track, "I_FREEMODE")
  -- FIPM has arbitrary overlapping vertical rectangles, not discrete lanes.
  if mode == 1 then return end
  local lane = mode == 2 and ((info >> 8) & 255) or -1
  if mode == 2 and lane >= r.GetMediaTrackInfo_Value(track, "I_NUMFIXEDLANES") then return end
  local time = r.GetSet_ArrangeView2(project, false, x, x + 1, 0, 0)
  if time < -EPS then return end
  return {track = track, lane = lane, time = math.max(0, time), x = x, y = y}
end

-- REAPER's native resize cursor belongs to the item edge. When the item is
-- not selected, the brush would otherwise win because selected_hover is false.
-- Convert the item start/end times to screen pixels and leave a small native
-- resize zone around both edges. This is hover-only; an owned brush stroke
-- keeps its brush cursor.
local function near_item_edge(x, y)
  if stroke or native_drag then return false end
  local item = r.GetItemFromPoint(x, y, true)
  if not item then return false end
  local ok, left, top, right, bottom = r.JS_Window_GetClientRect(arrange)
  if not ok or x < left or x >= right or y < top or y >= bottom then return false end
  local view_start, view_end = r.GetSet_ArrangeView2(project, false, 0, 0, 0, 0)
  local span, width = view_end - view_start, right - left
  if span <= EPS or width <= 1 then return false end
  local item_start = r.GetMediaItemInfo_Value(item, "D_POSITION")
  local item_end = item_start + r.GetMediaItemInfo_Value(item, "D_LENGTH")
  local start_x = left + (item_start - view_start) * width / span
  local end_x = left + (item_end - view_start) * width / span
  local zone = math.max(1, CONFIG.item_edge_zone)
  return math.abs(x - start_x) <= zone or math.abs(x - end_x) <= zone
end

-- Razor Edit ranges are stored per track as start/end/GUID triples in
-- P_RAZOREDITS. Preserve REAPER's native boundary cursor around every range
-- edge on the track under the pointer.
local function near_razor_edge(x, y, h)
  if stroke or native_drag or not h or not h.track then return false end
  local ok, razor = r.GetSetMediaTrackInfo_String(h.track, "P_RAZOREDITS", "", false)
  if not ok or not razor or razor == "" then return false end
  local rect_ok, left, top, right, bottom = r.JS_Window_GetClientRect(arrange)
  if not rect_ok or x < left or x >= right or y < top or y >= bottom then return false end
  local view_start, view_end = r.GetSet_ArrangeView2(project, false, 0, 0, 0, 0)
  local span, width = view_end - view_start, right - left
  if span <= EPS or width <= 1 then return false end
  local zone_time = math.max(1, CONFIG.razor_edge_zone) * span / width
  for start_text, end_text in razor:gmatch("([%-%d%.]+)%s+([%-%d%.]+)%s+[^%s]+") do
    local start_time, end_time = tonumber(start_text), tonumber(end_text)
    if start_time and end_time
      and (math.abs(h.time - start_time) <= zone_time
        or math.abs(h.time - end_time) <= zone_time) then
      return true
    end
  end
  return false
end

-- A dense Razor source may have no empty lane area where the Brush cursor can
-- appear. Keep Brush available over media items inside a media Razor range;
-- edge zones above still retain REAPER's native Razor resize cursor.
local function inside_razor(h, media_only)
  if not h or not h.track then return false end
  local ok, razor = r.GetSetMediaTrackInfo_String(h.track, "P_RAZOREDITS", "", false)
  if not ok or not razor or razor == "" then return false end
  for start_text, end_text, guid in razor:gmatch(
    "([%-%d%.]+)%s+([%-%d%.]+)%s+([^%s]+)") do
    local start_time, end_time = tonumber(start_text), tonumber(end_text)
    if (not media_only or guid == '""') and start_time and end_time
      and h.time >= start_time - EPS and h.time <= end_time + EPS then
      return true
    end
  end
  return false
end

local function inside_media_razor(h)
  return inside_razor(h, true)
end

local function clear_razor_edits()
  local tracks = {r.GetMasterTrack(project)}
  for track_index = 0, r.CountTracks(project) - 1 do
    tracks[#tracks + 1] = r.GetTrack(project, track_index)
  end
  local changed = false
  for _, track in ipairs(tracks) do
    local ok, razor = r.GetSetMediaTrackInfo_String(track, "P_RAZOREDITS", "", false)
    if ok and razor and razor ~= "" then changed = true; break end
  end
  if not changed then return false end
  r.Undo_BeginBlock2(project)
  for _, track in ipairs(tracks) do
    r.GetSetMediaTrackInfo_String(track, "P_RAZOREDITS", "", true)
  end
  r.Undo_EndBlock2(project, "Clear Razor Edits", -1)
  r.UpdateArrange()
  return true
end

-- While painting, use the nearest visible x at the same track/lane height.
-- GetClientRect returns SCREEN coordinates; right/bottom are exclusive.
-- This also keeps a release outside the horizontal edge in the same stroke.
local function stroke_hit(x, y, allow_scroll)
  local now = r.time_precise()
  local elapsed = math.min(0.05, math.max(0, now - (stroke.scroll_time or now)))
  stroke.scroll_time = now
  local ok, left, top, right, bottom = r.JS_Window_GetClientRect(arrange)
  if not ok or right - left < 4 or y < top or y >= bottom then return end
  -- One pixel inside the client area avoids edge borders and scrollbars.
  local sample_x = math.max(left + 1, math.min(right - 2, x))
  local h = hit(sample_x, y, true)
  if not h then return end
  if not allow_scroll or not CONFIG.edge_scroll or stroke.released then return h end
  -- Let pending stamps catch up before moving the view further.
  if qhead <= #queue then return h end
  local width = right - left
  local zone = math.max(1, math.min(CONFIG.edge_scroll_zone, width / 3))
  local direction, strength
  if x >= right - zone then
    direction, strength = 1, math.min(1, (x - (right - zone)) / zone)
  elseif x <= left + zone then
    direction, strength = -1, math.min(1, ((left + zone) - x) / zone)
  else
    return h
  end
  local start, stop = r.GetSet_ArrangeView2(project, false, 0, 0, 0, 0)
  if stop <= start or elapsed <= 0 then return h end
  -- Derive seconds/pixel from REAPER's actual coordinate mapping.
  local first = r.GetSet_ArrangeView2(project, false, left + 1, left + 2, 0, 0)
  local last = r.GetSet_ArrangeView2(project, false, right - 2, right - 1, 0, 0)
  local seconds_per_pixel = (last - first) / (width - 3)
  if seconds_per_pixel <= 0 then return h end
  local speed = CONFIG.edge_scroll_min_speed
    + (CONFIG.edge_scroll_max_speed - CONFIG.edge_scroll_min_speed) * strength
  local next_start = math.max(0, start + direction * speed * elapsed * seconds_per_pixel)
  if math.abs(next_start - start) <= EPS then return h end
  r.GetSet_ArrangeView2(project, true, 0, 0, next_start, next_start + stop - start)
  stroke.view_changed = true
  -- Re-read time AFTER scrolling: even a stationary pointer keeps painting.
  return hit(sample_x, y, true)
end

local function snap_left(time, bypass)
  if bypass or r.GetToggleCommandStateEx(0, 1157) ~= 1 then return time end
  local nearest = r.BR_GetClosestGridDivision(time)
  if math.abs(nearest - time) < EPS then return math.max(0, nearest) end
  return math.max(0, r.BR_GetPrevGridDivision(time))
end

local function prepare_chunk(chunk)
  -- Parse the source once per stroke; create directly at the final position.
  local output, depth = {}, 0
  for line in chunk:gmatch("([^\r\n]+)") do
    local token = line:match("^%s*(%S+)")
    local skip = depth == 1 and (token == "YPOS" or token == "FIXEDLANE"
      or token == "FIXEDLANEFLAGS" or token == "LANEPLAYS")
    local indent, key = line:match("^(%s*)([%u_]+)%s+{[^}]+}%s*$")
    if key == "GUID" or key == "IGUID" or key == "FXID" or key == "EGUID"
      or key == "POOLEDEVTS" then
      line = indent .. key .. " @BRUSH_GUID@"
    end
    if depth == 1 then
      if token == "POSITION" then line = "POSITION @BRUSH_POSITION@" end
      if token == "LENGTH" then line = "LENGTH @BRUSH_LENGTH@" end
      if token == "SEL" then line = "SEL 1" end
      if token == "GROUP" then line = "GROUP 0" end
      if token == "LOCK" then line = "LOCK 0" end
    end
    if not skip then output[#output + 1] = line end
    if token and token:sub(1, 1) == "<" then depth = depth + 1 end
    if token == ">" then depth = depth - 1 end
  end
  return table.concat(output, "\n") .. "\n"
end

local function make_chunk(chunk, start, length)
  return (chunk:gsub("@BRUSH_GUID@", function() return r.genGuid() end)
    :gsub("@BRUSH_POSITION@", string.format("%.17g", start))
    :gsub("@BRUSH_LENGTH@", string.format("%.17g", length)))
end

local function source_from_item(item)
  if not item or not r.ValidatePtr2(project, item, "MediaItem*") then return end
  local ok, chunk = r.GetItemStateChunk(item, "", false)
  if not ok or #chunk == 0 then error("Cannot read the source item state.") end
  local position = r.GetMediaItemInfo_Value(item, "D_POSITION")
  local length = r.GetMediaItemInfo_Value(item, "D_LENGTH")
  if length < EPS then return end
  local take = r.GetActiveTake(item)
  local beats = take and r.TakeIsMIDI(take)
  return {
    item = item, chunk = prepare_chunk(chunk), beats = beats, length = length,
    step = beats and (r.TimeMap2_timeToQN(project, position + length)
      - r.TimeMap2_timeToQN(project, position)) or length,
  }
end

-- A media Razor Edit is represented by a triple in P_RAZOREDITS whose third
-- field is an empty quoted GUID. Envelope Razor ranges carry an envelope GUID
-- and are deliberately left for the native edit behavior for now.
--
-- All media ranges are collected as one multi-track brush. Items must be fully
-- inside their range. This keeps the operation lossless and avoids silently
-- changing item/take offsets when a Razor boundary cuts an item.
local function source_from_razor()
  if not CONFIG.razor_source then return end
  local ranges = {}
  for track_index = 0, r.CountTracks(project) - 1 do
    local track = r.GetTrack(project, track_index)
    local ok, razor = r.GetSetMediaTrackInfo_String(track, "P_RAZOREDITS", "", false)
    if ok and razor and razor ~= "" then
      for start_text, end_text, guid in razor:gmatch(
        "([%-%d%.]+)%s+([%-%d%.]+)%s+([^%s]+)") do
        local start_time, end_time = tonumber(start_text), tonumber(end_text)
        if guid == '""' and start_time and end_time
          and end_time > start_time + EPS then
          ranges[#ranges + 1] = {
            track = track,
            track_index = track_index,
            start = start_time,
            stop = end_time,
          }
        end
      end
    end
  end
  if #ranges == 0 then return end

  local anchor_track_index = ranges[1].track_index
  local anchor_start, anchor_end = ranges[1].start, ranges[1].stop
  for _, range in ipairs(ranges) do
    anchor_track_index = math.min(anchor_track_index, range.track_index)
    anchor_start = math.min(anchor_start, range.start)
    anchor_end = math.max(anchor_end, range.stop)
  end

  local items = {}
  for _, range in ipairs(ranges) do
    range.track_index = range.track_index - anchor_track_index
    range.start_offset = range.start - anchor_start
    range.end_offset = range.stop - anchor_start
    range.items = {}
    for i = 0, r.CountTrackMediaItems(range.track) - 1 do
      local item = r.GetTrackMediaItem(range.track, i)
      local position = r.GetMediaItemInfo_Value(item, "D_POSITION")
      local length = r.GetMediaItemInfo_Value(item, "D_LENGTH")
      local finish = position + length
      if length > EPS and position >= range.start - EPS
        and finish <= range.stop + EPS then
        local chunk_ok, chunk = r.GetItemStateChunk(item, "", false)
        if not chunk_ok or #chunk == 0 then
          error("Cannot read a media item inside the Razor source.")
        end
        local part = {
          track_offset = range.track_index,
          chunk = prepare_chunk(chunk),
          offset = position - anchor_start,
          length = length,
        }
        range.items[#range.items + 1] = part
        items[#items + 1] = part
      end
    end
  end

  return {
    razor = true,
    beats = false,
    step = anchor_end - anchor_start,
    length = anchor_end - anchor_start,
    razor_ranges = ranges,
    razor_anchor_track_index = anchor_track_index,
    razor_anchor_start = anchor_start,
    razor_anchor_end = anchor_end,
    items = items,
  }
end

local function source_razor_contains(source, h)
  if not source or not source.razor or not h then return nil end
  for _, range in ipairs(source.razor_ranges) do
    if range.track == h.track and h.time >= range.start - EPS
      and h.time <= range.stop + EPS then
      return range
    end
  end
  return nil
end

-- Observe actual imported audio, rather than every change of selection.
-- A click/drag of an existing item still picks it through the original LMB path.
local function audio_identity(item)
  local take = r.GetActiveTake(item)
  if not take or r.TakeIsMIDI(take) then return end
  local source = r.GetMediaItemTake_Source(take)
  if not source then return end
  local root = source
  while r.GetMediaSourceParent(root) do root = r.GetMediaSourceParent(root) end
  local filename = r.GetMediaSourceFileName(root, "")
  if not filename or filename == "" then return end
  local _, guid = r.GetSetMediaItemInfo_String(item, "GUID", "", false)
  local _, take_guid = r.GetSetMediaItemTakeInfo_String(take, "GUID", "", false)
  -- Source identity detects replacing a take's file; take GUID detects a new take.
  -- Position/selection/volume are deliberately absent: editing does not pick audio.
  return guid, take_guid .. "\n" .. tostring(source) .. "\n" .. filename
end

local function remember_painted_item(item)
  local guid, identity = audio_identity(item)
  if guid then source_items[guid] = identity end
end

local function observe_imported_sample()
  if CONFIG.mode ~= "copy" or not CONFIG.auto_pick_imported_sample then return end
  local state = r.GetProjectStateChangeCount(project)
  if state == source_items_state then return end
  local initialized = source_items_state ~= nil
  local next_items, selected, hovered = {}, nil, nil
  local x, y = r.GetMousePosition()
  local under_mouse = r.JS_Window_FromPoint(x, y) == arrange
    and r.GetItemFromPoint(x, y, true) or nil
  for i = 0, r.CountMediaItems(project) - 1 do
    local item = r.GetMediaItem(project, i)
    local guid, identity = audio_identity(item)
    if guid then
      next_items[guid] = identity
      if initialized and source_items[guid] ~= identity
        and r.GetMediaItemInfo_Value(item, "D_LENGTH") > EPS then
        if item == under_mouse then hovered = item end
        if not selected and r.IsMediaItemSelected(item) then selected = item end
      end
    end
  end
  source_items, source_items_state = next_items, state
  -- The hovered changed item wins for drops onto an existing item. Otherwise use
  -- the newly inserted selected item, not the first item in the whole selection.
  local item = hovered or selected
  if initialized and item and not stroke and not eraser then
    source_cache = source_from_item(item) or source_cache
  end
end

local function template(h)
  if CONFIG.mode == "copy" then
    local razor_source = source_from_razor()
    if razor_source then return razor_source end
    -- The explicitly clicked source takes priority over a multi-item selection.
    -- Painting itself changes selection, but must not change the brush source.
    if source_cache then
      if r.ValidatePtr2(project, source_cache.item, "MediaItem*") then
        source_cache = source_from_item(source_cache.item)
      end
      if source_cache then return source_cache end
    end
    local item = r.GetSelectedMediaItem(project, 0)
    if item then
      source_cache = source_from_item(item)
      if source_cache then return source_cache end
    end
  end
  local numerator, denominator = r.TimeMap_GetTimeSigAtTime(project, h.time)
  return {beats = true, step = numerator * 4 / denominator * CONFIG.fallback_bars,
    blank = CONFIG.mode == "empty" and "empty" or "midi"}
end

-- Keep source duration; quantize each following start upward, avoiding drift.
local function source_end(start)
  if stroke.source.beats then
    return r.TimeMap2_QNToTime(stroke.project,
      r.TimeMap2_timeToQN(stroke.project, start) + stroke.source.step)
  end
  return start + stroke.source.step
end

local function grid_up(time)
  local nearest = r.BR_GetClosestGridDivision(time)
  if math.abs(nearest - time) <= EPS then return nearest end
  return r.BR_GetNextGridDivision(time)
end

local function grid_down(time)
  if time < 0 then return time end
  local nearest = r.BR_GetClosestGridDivision(time)
  if math.abs(nearest - time) <= EPS then return nearest end
  return r.BR_GetPrevGridDivision(time)
end

local function repeat_position(index)
  if stroke.positions[index] then return stroke.positions[index] end
  while index > stroke.position_max do
    local previous = stroke.positions[stroke.position_max]
    local following = grid_up(source_end(previous))
    if following <= previous + EPS then following = r.BR_GetNextGridDivision(previous + EPS) end
    if following <= previous + EPS then error("Grid did not advance.") end
    stroke.position_max = stroke.position_max + 1
    stroke.positions[stroke.position_max] = following
  end
  while index < stroke.position_min do
    local following = stroke.positions[stroke.position_min]
    local ideal = stroke.source.beats and r.TimeMap2_QNToTime(stroke.project,
      r.TimeMap2_timeToQN(stroke.project, following) - stroke.source.step)
      or following - stroke.source.step
    local previous = grid_down(ideal)
    if previous >= following - EPS then previous = ideal end
    if previous >= following - EPS then error("Grid did not move backwards.") end
    stroke.position_min = stroke.position_min - 1
    stroke.positions[stroke.position_min] = previous
  end
  return stroke.positions[index]
end

local function grid_index(time)
  while stroke.positions[stroke.position_max] <= time + EPS do
    repeat_position(stroke.position_max + 1)
  end
  while stroke.positions[stroke.position_min] > time + EPS do
    repeat_position(stroke.position_min - 1)
  end
  local lo, hi = stroke.position_min, stroke.position_max + 1
  while lo + 1 < hi do
    local mid = (lo + hi) // 2
    if stroke.positions[mid] <= time + EPS then lo = mid else hi = mid end
  end
  return lo
end

local function times(index)
  if stroke.snap then
    local start = repeat_position(index)
    return start, source_end(start)
  end
  local start = stroke.anchor + index * stroke.source.step
  local stop = start + stroke.source.step
  if stroke.source.beats then
    return r.TimeMap2_QNToTime(stroke.project, start), r.TimeMap2_QNToTime(stroke.project, stop)
  end
  return start, stop
end

local function lane_key(track, lane)
  return tostring(track) .. ":" .. lane
end

local function occupied_ranges(track, lane)
  local key = lane_key(track, lane)
  if stroke.occupied[key] then return stroke.occupied[key] end
  local ranges = {}
  for i = 0, r.CountTrackMediaItems(track) - 1 do
    local item = r.GetTrackMediaItem(track, i)
    if lane < 0 or r.GetMediaItemInfo_Value(item, "I_FIXEDLANE") == lane then
      local pos = r.GetMediaItemInfo_Value(item, "D_POSITION")
      local finish = pos + r.GetMediaItemInfo_Value(item, "D_LENGTH")
      if finish > pos + EPS then ranges[#ranges + 1] = {start = pos, stop = finish} end
    end
  end
  table.sort(ranges, function(a, b) return a.start < b.start end)
  local merged = {}
  for _, range in ipairs(ranges) do
    local previous = merged[#merged]
    if previous and range.start <= previous.stop + EPS then
      previous.stop = math.max(previous.stop, range.stop)
    else
      merged[#merged + 1] = range
    end
  end
  stroke.occupied[key] = merged
  return merged
end

local function insertion_point(ranges, start)
  local lo, hi = 1, #ranges + 1
  while lo < hi do
    local mid = (lo + hi) // 2
    if ranges[mid].stop <= start + EPS then lo = mid + 1 else hi = mid end
  end
  return lo
end

local function add_range(ranges, start, stop, index)
  if index > 1 and ranges[index - 1].stop >= start - EPS then
    index = index - 1
    ranges[index].stop = math.max(ranges[index].stop, stop)
  else
    table.insert(ranges, index, {start = start, stop = stop})
  end
  while ranges[index + 1] and ranges[index + 1].start <= ranges[index].stop + EPS do
    ranges[index].stop = math.max(ranges[index].stop, ranges[index + 1].stop)
    table.remove(ranges, index + 1)
  end
end

local function begin_undo()
  if not stroke.undo then
    r.Undo_BeginBlock2(stroke.project)
    stroke.undo = true
  end
end

local function media_track_index(track)
  local number = r.GetMediaTrackInfo_Value(track, "IP_TRACKNUMBER")
  if number and number >= 1 then return math.floor(number) - 1 end
  return nil
end

local function stamp(job, index)
  if not r.ValidatePtr2(stroke.project, job.track, "MediaTrack*") then return end
  local start, stop = times(index)
  if start < -EPS or stop <= start + EPS then return end
  start = math.max(0, start)
  local ranges = occupied_ranges(job.track, job.lane)
  if stroke.source.razor then
    local target_track_index = stroke.source.razor_anchor_track_index
    if not target_track_index then return false end
    local delta = start - stroke.source.razor_anchor_start
    delta = math.max(-stroke.source.razor_anchor_start, delta)
    shift_razor_state(stroke.razor_state, delta)

    -- Build one collision cache per destination track. Items inside the Razor
    -- source may overlap and must be copied as a group, so newly-created
    -- siblings are not treated as collisions.
    local target_plans = {}
    for _, part in ipairs(stroke.source.items) do
      local destination_track = r.GetTrack(project,
        target_track_index + part.track_offset)
      if destination_track then
        local key = lane_key(destination_track, job.lane)
        local plan = target_plans[key]
        if not plan then
          plan = {track = destination_track, lane = job.lane,
            ranges = occupied_ranges(destination_track, job.lane), items = {}}
          target_plans[key] = plan
        end
        local item_start = start + part.offset
        local item_stop = item_start + part.length
        local where = insertion_point(plan.ranges, item_start)
        if item_start >= -EPS and item_stop > item_start + EPS
          and not (plan.ranges[where]
            and plan.ranges[where].start < item_stop - EPS) then
          plan.items[#plan.items + 1] = {
            chunk = part.chunk, start = math.max(0, item_start),
            length = item_stop - item_start,
          }
        end
      end
    end
    local plan_count = 0
    for _, plan in pairs(target_plans) do
      if #plan.items > 0 then plan_count = plan_count + 1 end
    end
    if plan_count == 0 then return false end
    begin_undo()
    if not stroke.selection_started then
      r.SelectAllMediaItems(stroke.project, false)
      stroke.selection_started = true
    end
    local changed = false
    for _, plan in pairs(target_plans) do
      for _, part in ipairs(plan.items) do
        local item = r.AddMediaItemToTrack(plan.track)
        if not item then error("Cannot create a Razor source item.") end
        if not r.SetItemStateChunk(item,
          make_chunk(part.chunk, part.start, part.length), false) then
          r.DeleteTrackMediaItem(plan.track, item)
          error("Cannot apply a Razor source item state.")
        end
        r.SetMediaItemInfo_Value(item, "B_UISEL", 1)
        r.SetMediaItemInfo_Value(item, "C_LOCK", 0)
        r.SetMediaItemInfo_Value(item, "I_GROUPID", 0)
        if plan.lane >= 0
          and r.GetMediaTrackInfo_Value(plan.track, "I_FREEMODE") == 2 then
          r.SetMediaItemInfo_Value(item, "I_FIXEDLANE", plan.lane)
        end
        remember_painted_item(item)
        changed = true
      end
    end
    -- Add all copied ranges after creation, allowing overlapping source items
    -- while still preventing overlap with pre-existing target items.
    for _, plan in pairs(target_plans) do
      for _, part in ipairs(plan.items) do
        local where = insertion_point(plan.ranges, part.start)
        add_range(plan.ranges, part.start, part.start + part.length, where)
      end
    end
    -- Adding media items can make REAPER clear Razor Edits. Restore the
    -- complete shifted state after the batch, not just before it.
    shift_razor_state(stroke.razor_state, delta)
    return changed
  end
  local where = insertion_point(ranges, start)
  if ranges[where] and ranges[where].start < stop - EPS then return false end
  begin_undo()
  if not stroke.selection_started then
    r.SelectAllMediaItems(stroke.project, false)
    stroke.selection_started = true
  end
  local item
  if stroke.source.chunk then
    item = r.AddMediaItemToTrack(job.track)
    if not item then error("Cannot create item.") end
    if not r.SetItemStateChunk(item, make_chunk(stroke.source.chunk, start, stop - start), false) then
      -- Remove only the failed new object; existing items are never deleted.
      r.DeleteTrackMediaItem(job.track, item)
      error("Cannot apply source item state.")
    end
  elseif stroke.source.blank == "midi" then
    item = r.CreateNewMIDIItemInProj(job.track, start, stop, false)
  else
    item = r.AddMediaItemToTrack(job.track)
    if item then
      r.SetMediaItemPosition(item, start, false)
      r.SetMediaItemLength(item, stop - start, false)
    end
  end
  if not item then error("Cannot create item.") end
  r.SetMediaItemInfo_Value(item, "B_UISEL", 1)
  r.SetMediaItemInfo_Value(item, "C_LOCK", 0)
  r.SetMediaItemInfo_Value(item, "I_GROUPID", 0)
  -- Never write -1: only place into an already existing fixed lane.
  if job.lane >= 0 and r.GetMediaTrackInfo_Value(job.track, "I_FREEMODE") == 2 then
    r.SetMediaItemInfo_Value(item, "I_FIXEDLANE", job.lane)
  end
  remember_painted_item(item)
  add_range(ranges, start, stop, where)
  return true
end

-- Keep the visible Razor range aligned with the current brush cell, even when
-- the stamp queue is temporarily behind because of the frame budget.
local function follow_razor_hit(h)
  if not stroke or not stroke.source.razor or not h then return end
  local index
  if stroke.snap then
    index = grid_index(h.time)
  else
    local coordinate = stroke.source.beats and r.TimeMap2_timeToQN(project, h.time)
      or h.time
    index = math.floor((coordinate - stroke.mouse_anchor) / stroke.source.step + EPS)
  end
  local start = stroke.snap and repeat_position(index)
    or stroke.anchor + index * stroke.source.step
  start = math.max(0, start)
  local target_track_index = media_track_index(h.track)
  if not target_track_index then return end
  if stroke.source.razor then
    target_track_index = stroke.source.razor_anchor_track_index
    local delta = start - stroke.source.razor_anchor_start
    delta = math.max(-stroke.source.razor_anchor_start, delta)
    shift_razor_state(stroke.razor_state, delta)
  end
end

local function enqueue(h)
  if not h then stroke.last = nil; return end
  local track, lane = h.track, h.lane
  if stroke.source.razor then
    track = r.GetTrack(project, stroke.source.razor_anchor_track_index)
    lane = stroke.razor_drag_lane
    if not track then stroke.last = nil; return end
  end
  local coordinate = stroke.source.beats and r.TimeMap2_timeToQN(project, h.time) or h.time
  local index = stroke.snap and grid_index(h.time)
    or math.floor((coordinate - stroke.mouse_anchor) / stroke.source.step + EPS)
  local key = lane_key(track, lane)
  if stroke.last and stroke.last.key == key and stroke.last.index == index then return end
  local first = index
  if stroke.last and stroke.last.key == key then
    first = stroke.last.index
    if stroke.razor_drag and stroke.last.index == 0 then
      if index > 0 then first = 1
      elseif index < 0 then first = -1
      else return end
    end
  end
  local direction = index >= first and 1 or -1
  -- Store a whole traversed range: fast jumps lose no cells and need no huge queue.
  queue[#queue + 1] = {track = track, lane = lane, key = key,
    next_index = first, last_index = index, direction = direction}
  stroke.last = {key = key, index = index}
end

local function drain(limit)
  if qhead > #queue then
    if stroke.view_changed then r.UpdateArrange(); stroke.view_changed = nil end
    return
  end
  if r.GetProjectStateChangeCount(project) ~= stroke.cache_state then stroke.occupied = {} end
  local count, changed = 0, false
  local deadline = limit == math.huge and math.huge or r.time_precise() + CONFIG.frame_budget
  r.PreventUIRefresh(1)
  local ok, err = xpcall(function()
    while qhead <= #queue and count < limit do
      local job = queue[qhead]
      local visited = stroke.visited[job.key]
      if not visited then visited = {}; stroke.visited[job.key] = visited end
      local index = job.next_index
      if not visited[index] then
        visited[index] = true
        if stamp(job, index) then changed = true end
      end
      if index == job.last_index then qhead = qhead + 1
      else job.next_index = index + job.direction end
      count = count + 1
      if r.time_precise() >= deadline then break end
    end
  end, debug.traceback)
  r.PreventUIRefresh(-1)
  stroke.cache_state = r.GetProjectStateChangeCount(project)
  -- Every painted audio item was registered above; no project-wide rescan.
  source_items_state = stroke.cache_state
  if qhead > #queue then queue, qhead = {}, 1 end
  -- Exactly one redraw per changed batch; no per-item/idle redraws.
  if changed or stroke.view_changed then r.UpdateArrange() end
  stroke.view_changed = nil
  if not ok then error(err) end
end

local function begin_stroke(h, bypass, source_override, razor_drag)
  local razor_state = capture_razor_state()
  local source = source_override or template(h)
  if not source or source.step < EPS then return false end
  -- A click-placement Razor brush starts on the project grid. A drag that
  -- begins inside the existing Razor keeps its exact source position and
  -- moves in literal Razor-width steps.
  local start = source.razor and
    (razor_drag and source.razor_anchor_start or snap_left(h.time, bypass))
    or snap_left(h.time, bypass)
  stroke = {project = project, source = source, visited = {}, occupied = {},
    razor_state = razor_state,
    razor_drag = source.razor and razor_drag or false,
    razor_drag_lane = source.razor and razor_drag and h.lane or -1,
    scroll_time = r.time_precise(),
    snap = not bypass and (not source.razor or not razor_drag)
      and r.GetToggleCommandStateEx(0, 1157) == 1,
    positions = {[0] = start}, position_min = 0, position_max = 0,
    cache_state = r.GetProjectStateChangeCount(project),
    anchor = source.beats and r.TimeMap2_timeToQN(project, start) or start,
    mouse_anchor = source.beats and r.TimeMap2_timeToQN(project, h.time) or h.time}
  if stroke.razor_drag then
    -- Index zero is the already-existing source Razor. It is an origin, not
    -- a new stamp; the first copy is made only after one full Razor width.
    local anchor_track = r.GetTrack(project, source.razor_anchor_track_index)
    stroke.last = {key = lane_key(anchor_track, stroke.razor_drag_lane), index = 0}
  else
    enqueue(h)
  end
  return true
end

