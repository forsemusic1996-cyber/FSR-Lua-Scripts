local function event_list()
  local events = {}
  for order, msg in ipairs(messages) do
    local ok, _, timestamp, wlow, whigh, x, y = r.JS_WindowMessage_Peek(arrange, msg)
    if ok and timestamp and timestamp > (seen[msg] or 0) then
      seen[msg] = timestamp
      events[#events + 1] = {msg = msg, time = timestamp, wlow = wlow,
        whigh = whigh, x = x, y = y, order = order}
    end
  end
  table.sort(events, function(a, b)
    if a.time == b.time then return a.order < b.order end
    return a.time < b.time
  end)
  return events
end

