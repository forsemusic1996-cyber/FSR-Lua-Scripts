-- Creating media items can make REAPER clear P_RAZOREDITS. Keep a private
-- snapshot for the active brush stroke so the complete Razor selection can be
-- shifted from one stable template, regardless of how many tracks it covers.
local function capture_razor_state()
  local state = {}
  for track_index = 0, r.CountTracks(project) - 1 do
    local track = r.GetTrack(project, track_index)
    local ok, razor = r.GetSetMediaTrackInfo_String(track, "P_RAZOREDITS", "", false)
    if ok and razor and razor ~= "" then state[track] = razor end
  end
  return state
end

local function shift_razor_state(state, delta)
  if not state then return end
  for track, razor in pairs(state) do
    local parts = {}
    for start_text, end_text, guid in razor:gmatch(
      "([%-%d%.]+)%s+([%-%d%.]+)%s+([^%s]+)") do
      local start_time, end_time = tonumber(start_text), tonumber(end_text)
      if start_time and end_time then
        parts[#parts + 1] = string.format("%.17g %.17g %s",
          start_time + delta, end_time + delta, guid)
      end
    end
    if #parts > 0 then
      r.GetSetMediaTrackInfo_String(track, "P_RAZOREDITS",
        table.concat(parts, " "), true)
    end
  end
end

local function move_razor_sources(state, source_ranges, target_track_index,
  target_start)
  if not state or not source_ranges or #source_ranges == 0
    or not target_track_index then return end
  local entries_by_track = {}
  for track, razor in pairs(state) do
    local entries = {}
    for start_text, end_text, guid in razor:gmatch(
      "([%-%d%.]+)%s+([%-%d%.]+)%s+([^%s]+)") do
      local start_time, end_time = tonumber(start_text), tonumber(end_text)
      local is_source = false
      if guid == '""' and start_time and end_time then
        for _, source_range in ipairs(source_ranges) do
          if track == source_range.track
            and math.abs(start_time - source_range.start) <= EPS
            and math.abs(end_time - source_range.stop) <= EPS then
            is_source = true
            break
          end
        end
      end
      if not is_source then
        entries[#entries + 1] = {start = start_time, stop = end_time, guid = guid}
      end
    end
    entries_by_track[track] = entries
  end
  for _, source_range in ipairs(source_ranges) do
    local target_index = target_track_index + source_range.track_index
    local destination_track = r.GetTrack(project, target_index)
    if destination_track then
      local target_entries = entries_by_track[destination_track] or {}
      target_entries[#target_entries + 1] = {
        start = target_start + source_range.start_offset,
        stop = target_start + source_range.end_offset,
        guid = '""'}
      entries_by_track[destination_track] = target_entries
    end
  end

  for track, entries in pairs(entries_by_track) do
    local parts = {}
    for _, entry in ipairs(entries) do
      parts[#parts + 1] = string.format("%.17g %.17g %s",
        entry.start, entry.stop, entry.guid)
    end
    r.GetSetMediaTrackInfo_String(track, "P_RAZOREDITS", table.concat(parts, " "), true)
  end
end

-- While dragging from Media Explorer, REAPER can report a generic
-- Windows.UI.Core.CoreWindow under the pointer. The keyboard focus remains
-- on the file list, so latch this source state until the physical LMB release.
local function focus_is_media_explorer()
  local hwnd = r.JS_Window_GetFocus()
  for _ = 1, 12 do
    if not hwnd or not r.JS_Window_IsWindow(hwnd) then return false end
    if r.JS_Window_GetClassName(hwnd) == "REAPERMediaExplorerMainwnd" then
      return true
    end
    local parent = r.JS_Window_GetParent(hwnd)
    if parent == hwnd then break end
    hwnd = parent
  end
  return false
end

